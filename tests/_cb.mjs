import { chromium } from "/opt/node-tools/node_modules/playwright/index.mjs";
import { serve } from "./serve.mjs";
const D = "/tmp/claude-0/-home-user/4e0467e9-9961-5b44-a7bf-80314e4c07a9/scratchpad/aw";
const { server, url } = serve();
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, reducedMotion: "reduce" })).newPage();
page.on("pageerror", (e) => console.log("ERR", e.message));
await page.goto(url + "#portfolio", { timeout: 120000 });
await page.waitForFunction(() => document.body.classList.contains("loaded"), null, { timeout: 180000 });
await page.waitForTimeout(4000);
await page.evaluate(() => (location.hash = "#bio"));
await page.waitForTimeout(9000);
await page.screenshot({ path: `${D}/cb-bio.png` });
await page.evaluate(() => (location.hash = "#contact"));
await page.waitForTimeout(9000);
await page.screenshot({ path: `${D}/cb-contact.png` });
await browser.close(); server.close();
